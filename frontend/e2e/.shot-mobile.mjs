import { chromium, devices } from "@playwright/test";
import { config } from "dotenv";
config({ path: ".env.e2e.local" });
const OUT = "/private/tmp/claude-501/-Users-allamtharun-Desktop-Resume-optimizer/2ea338f1-dcff-455f-87b6-2717a971584d/scratchpad/shots";
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices["Pixel 7"], colorScheme: "dark" });
const page = await ctx.newPage();
await page.goto("http://localhost:3000/login");
await page.getByLabel("Email").fill(process.env.E2E_EMAIL);
await page.getByLabel("Password").fill(process.env.E2E_PASSWORD);
await page.getByRole("main").getByRole("button", { name: "Sign in", exact: true }).click();
await page.getByText("Recent analyses").waitFor();
await page.goto("http://localhost:3000/analysis/" + process.argv[2]);
await page.getByRole("img", { name: /Job fit/ }).first().waitFor({ timeout: 90000 });
await page.getByRole("button", { name: "Explain", exact: true }).nth(4).click();
await page.getByRole("region", { name: "Explanation" }).first().waitFor({ timeout: 60000 });
await page.waitForTimeout(600);
await page.screenshot({ path: `${OUT}/mobile-overview.png`, fullPage: true });
await browser.close();
